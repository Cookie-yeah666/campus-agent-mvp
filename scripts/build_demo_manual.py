def add_heading(doc, text: str, level: int, newpage: bool = True) -> None:
    paragraph = doc.add_paragraph(style=f"Heading {level}")
    if level == 1:
        # 核心章节另起一页；后半部分短章节连续排版，避免整页留白
        paragraph.paragraph_format.page_break_before = newpage
    set_paragraph_spacing(
        paragraph,
        before=16 if level == 1 else 12,
        after=8 if level == 1 else 5,
        line=1.2,
    )
    add_rich(paragraph, text, size={1: 18, 2: 13.5, 3: 11.5}[level], color={1: "1F3A5F", 2: INDIGO, 3: INK}[level])
    if level == 1:
        p_pr = paragraph._p.get_or_add_pPr()
        borders = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "8")
        bottom.set(qn("w:space"), "4")
        bottom.set(qn("w:color"), LINE)
        borders.append(bottom)
        p_pr.append(borders)


def add_field(paragraph, instruction: str, placeholder: str = "1") -> None:
    """写入标准 OOXML 域：begin / instr / separate / 缓存结果 / end 分 run。"""
    begin_run = paragraph.add_run()
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    begin_run._r.append(begin)

    instr_run = paragraph.add_run()
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = instruction
    instr_run._r.append(instr)

    separate_run = paragraph.add_run()
    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    separate_run._r.append(separate)

    result_run = paragraph.add_run(placeholder)
    set_font(result_run, FONT, 8, "9AA3AF")

    end_run = paragraph.add_run()
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    end_run._r.append(end)


