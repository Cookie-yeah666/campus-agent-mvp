def add_code(doc, content: str) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    fixed_layout(table)
    set_table_borders(table, color="E6E1D6", size=4)
    set_cell_margins(table, 100, 100, 140, 140)
    no_split(table.rows[0])
    cell = table.rows[0].cells[0]
    cell.width = Cm(16.6)
    shade_cell(cell, "F6F4EE")
    first = True
    for line in content.splitlines():
        paragraph = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        set_paragraph_spacing(paragraph, before=0, after=0, line=1.15)
        run = paragraph.add_run(line if line else " ")
        set_font(run, CODE_FONT, 8.4, "33465E")
        run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), FONT)
        if line.startswith(" "):
            run._element.set(qn("xml:space"), "preserve")
    add_spacer(doc)


