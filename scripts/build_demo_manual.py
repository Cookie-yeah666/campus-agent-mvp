def build_markdown() -> None:
    lines: list[str] = []
    lines.extend(
        [
            "# 知行 · 校园智能服务助手",
            "",
            "## 演示手册",
            "",
            "> 双 Agent · RAG 引用 · 工作流编排 · 幂等与审计",
            ">",
            "> 团队：嵇杨健、陈昱麒、王祥晔 ｜ 指导教师：刘 安 ｜ 版本：v1.1 · 2026 年 11 月",
            "",
            "---",
            "",
        ]
    )
    for block in Blocks:
        kind = block[0]
        if kind == "h1":
            lines.extend(["", f"# {block[1]}", ""])
        elif kind == "h2":
            lines.extend(["", f"## {block[1]}", ""])
        elif kind == "h3":
            lines.extend(["", f"### {block[1]}", ""])
        elif kind == "p":
            lines.extend([block[1], ""])
        elif kind == "quote":
            lines.extend([f"> **讲解词｜** {block[1]}", ""])
        elif kind == "bullets":
            lines.extend([f"- {item}" for item in block[1]])
            lines.append("")
        elif kind == "numbers":
            lines.extend([f"{index + 1}. {item}" for index, item in enumerate(block[1])])
            lines.append("")
        elif kind == "table":
            headers, rows = block[1], block[2]
            lines.append("| " + " | ".join(headers) + " |")
            lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
            for row in rows:
                lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
            lines.append("")
        elif kind == "callout":
            color = {"info": "提示", "warn": "注意", "success": "结论"}[block[1]]
            lines.extend([f"> **{color}｜{block[2]}**", ">", f"> {block[3]}", ""])
        elif kind == "code":
            lines.extend(["```text", block[1], "```", ""])
        elif kind == "pagebreak":
            lines.extend(["---", ""])
        elif kind == "image":
            relative = block[1] if "/" in block[1] else f"screenshots/{block[1]}"
            lines.extend([f"![{block[2]}]({relative})", "", f"*{block[2]}*", ""])
        elif kind == "checklist":
            lines.extend([f"- [ ] {item}" for item in block[1]])
            lines.append("")

    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"Markdown saved: {OUT_MD}")


