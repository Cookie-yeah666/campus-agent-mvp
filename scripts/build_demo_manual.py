def build_docx() -> None:
    doc = Document()
    section = doc.sections[0]
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(1.9)
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(2.2)
    style_document(doc)
    build_cover(doc)

    # 页眉页脚（首页除外）
    header = section.header
    header_paragraph = header.paragraphs[0]
    header_paragraph.text = ""
    header_paragraph.paragraph_format.tab_stops.add_tab_stop(Cm(16.6), alignment=2)
    run = header_paragraph.add_run("知行 · 校园智能服务助手")
    set_font(run, FONT, 8, "75808F")
    run = header_paragraph.add_run("\t演示手册 v1.1")
    set_font(run, FONT, 8, "9AA3AF")

    footer = section.footer
    footer_paragraph = footer.paragraphs[0]
    footer_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = footer_paragraph.add_run("第 ")
    set_font(run, FONT, 8, "9AA3AF")
    add_field(footer_paragraph, " PAGE ")
    run = footer_paragraph.add_run(" 页 / 共 ")
    set_font(run, FONT, 8, "9AA3AF")
    add_field(footer_paragraph, " NUMPAGES ")
    run = footer_paragraph.add_run(" 页")
    set_font(run, FONT, 8, "9AA3AF")

    add_heading.first = False
    for block in Blocks:
        kind = block[0]
        if kind == "h1":
            add_heading(doc, block[1], 1, block[2])
        elif kind == "h2":
            add_heading(doc, block[1], 2)
        elif kind == "h3":
            add_heading(doc, block[1], 3)
        elif kind == "p":
            paragraph = doc.add_paragraph()
            set_paragraph_spacing(paragraph)
            add_rich(paragraph, block[1], size=10.5, color=INK)
        elif kind == "quote":
            add_quote(doc, block[1])
        elif kind == "bullets":
            for item in block[1]:
                paragraph = doc.add_paragraph(style="List Bullet")
                set_paragraph_spacing(paragraph, after=2, line=1.3)
                add_rich(paragraph, item, size=10.2, color=INK)
        elif kind == "numbers":
            for item in block[1]:
                paragraph = doc.add_paragraph(style="List Number")
                set_paragraph_spacing(paragraph, after=2, line=1.3)
                add_rich(paragraph, item, size=10.2, color=INK)
