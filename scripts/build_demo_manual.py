def add_table(doc, headers: list[str], rows: list[list[str]], widths: list[float] | None) -> None:
    cols = len(headers)
    table = doc.add_table(rows=1, cols=cols)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    fixed_layout(table)
    set_table_borders(table)
    set_cell_margins(table)
    if widths:
        total = sum(widths)
        widths = [w * 16.6 / total for w in widths]
    else:
        widths = [16.6 / cols] * cols
    for index, width in enumerate(widths):
        table.columns[index].width = Cm(width)

    header_row = table.rows[0]
    set_repeat_header(header_row)
    no_split(header_row)
    for index, title in enumerate(headers):
        cell = header_row.cells[index]
        cell.width = Cm(widths[index])
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        shade_cell(cell, INK)
        paragraph = cell.paragraphs[0]
        set_paragraph_spacing(paragraph, after=0, line=1.15)
        run = paragraph.add_run(title)
        run.bold = True
        set_font(run, FONT, 9.0, "FFFFFF")

    for row_index, values in enumerate(rows):
        row = table.add_row()
        no_split(row)
        for index, value in enumerate(values):
            cell = row.cells[index]
            cell.width = Cm(widths[index])
            cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP
            if row_index % 2 == 1:
                shade_cell(cell, "F8F7F2")
            paragraph = cell.paragraphs[0]
            set_paragraph_spacing(paragraph, after=0, line=1.2)
            add_rich(paragraph, str(value), size=8.8, color=INK)

    add_spacer(doc)


